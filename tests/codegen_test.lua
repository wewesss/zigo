return function(env)
    local test, z = env.test, env.z
    local assertTrue, assertFalse, assertEq = env.assertTrue, env.assertFalse, env.assertEq
    local assertThrows = env.assertThrows

    local huge = math.huge
    local nan = 0 / 0

    local function withConfig(flag, fn)
        local previous = z.config().codegen
        z.config({ codegen = flag })
        local ok, err = pcall(fn)
        z.config({ codegen = previous })
        if not ok then error(err, 0) end
    end

    local function withoutLoader(replacement, fn)
        local savedLoad, savedLoadstring = load, loadstring
        load, loadstring = replacement, replacement
        local ok, err = pcall(fn)
        load, loadstring = savedLoad, savedLoadstring
        if not ok then error(err, 0) end
    end

    local function compiled(flag, build)
        local fn
        withConfig(flag, function() fn = build()._test end)
        return fn
    end

    local function sameVerdict(build, values)
        local generated = compiled(true, build)
        local reference = compiled(false, build)
        assertTrue(z._isGenerated(generated))
        assertFalse(z._isGenerated(reference))
        for i = 1, values.n do
            local v = values[i]
            assertEq(generated(v), reference(v))
        end
    end

    local function listOf(...)
        local t = { ... }
        t.n = select("#", ...)
        return t
    end

    local hostileKeys = {
        "]] os.exit() --",
        "]==] os.exit() --[==[",
        "\0",
        "\0001",
        "a\"b",
        "a'b",
        "a\nb",
        "a\r\nb",
        "\\",
        "x\\\"; os.exit() --",
        "\226\130\172",
        "",
    }

    local function withExitCanary(fn)
        local realExit = os.exit
        local called = false
        os.exit = function() called = true end
        local ok, err = pcall(fn)
        os.exit = realExit
        if not ok then error(err, 0) end
        assertFalse(called)
    end

    test("codegen: _test is generated by default for every node kind", function()
        withConfig(true, function()
            local nodes = {
                z.string():min(1), z.number():max(3), z.integer(), z.integer({ strict = true }),
                z.boolean(), z.literal("a"), z.literal(2), z.literal(true), z.enum({ "a", 2, false }),
                z.any(), z.unknown(), z.never(), z.array(z.string()), z.object({ a = z.string() }),
                z.string():optional(), z.object({}):optional(), z.array(z.any()):optional(),
            }
            for i = 1, #nodes do assertTrue(z._isGenerated(nodes[i]._test)) end
        end)
    end)

    test("codegen: hostile keys never reach the generated code as code", function()
        withConfig(true, function()
            withExitCanary(function()
                for i = 1, #hostileKeys do
                    local key = hostileKeys[i]
                    local S = z.object({ [key] = z.string() })
                    assertTrue(z._isGenerated(S._test))
                    assertTrue(S:is({ [key] = "x" }))
                    assertFalse(S:is({}))
                    assertFalse(S:is({ [key] = 1 }))
                    local strict = S:strict()
                    assertTrue(strict:is({ [key] = "x" }))
                    assertFalse(strict:is({ [key] = "x", other = 1 }))
                    local viaMeta = setmetatable({}, { __index = { [key] = 4 } })
                    assertTrue(z.object({ [key] = z.integer() }, { meta = true }):is(viaMeta))
                    assertFalse(z.object({ [key] = z.integer() }):is(viaMeta))
                end
            end)
        end)
    end)

    test("codegen: hostile literals and enum members are compared, not executed", function()
        withConfig(true, function()
            withExitCanary(function()
                for i = 1, #hostileKeys do
                    local s = hostileKeys[i]
                    local L = z.literal(s)
                    assertTrue(z._isGenerated(L._test))
                    assertTrue(L:is(s))
                    assertFalse(L:is(s .. "x"))
                    local E = z.enum({ s, "other" })
                    assertTrue(z._isGenerated(E._test))
                    assertTrue(E:is(s))
                    assertFalse(E:is(s .. "x"))
                end
            end)
        end)
    end)

    test("codegen: one megabyte key, literal and enum member", function()
        withConfig(true, function()
            withExitCanary(function()
                local big = ("k"):rep(1024 * 1024)
                local S = z.object({ [big] = z.literal(big) })
                assertTrue(z._isGenerated(S._test))
                assertTrue(S:is({ [big] = big }))
                assertFalse(S:is({ [big] = big .. "x" }))
                assertFalse(S:is({}))
                local nasty = ("]] os.exit() --"):rep(65536)
                local E = z.enum({ nasty, "a" })
                assertTrue(z._isGenerated(E._test))
                assertTrue(E:is(nasty))
                assertFalse(E:is("a" .. nasty))
            end)
        end)
    end)

    test("codegen: numeric bounds beyond the inline constant limit", function()
        withConfig(true, function()
            local shape, valid, invalid = {}, {}, {}
            for i = 1, 70 do
                local key = "f" .. i
                shape[key] = z.integer():between(i, i + 1)
                valid[key] = i
                invalid[key] = i
            end
            invalid.f70 = 99
            local S = z.object(shape)
            assertTrue(z._isGenerated(S._test))
            assertTrue(S:is(valid))
            assertFalse(S:is(invalid))
        end)
    end)

    test("codegen: falls back to closures when load and loadstring are missing", function()
        withConfig(true, function()
            withoutLoader(nil, function()
                local S = z.object({ a = z.string():min(2), b = z.array(z.integer()):optional() }):strict()
                assertFalse(z._isGenerated(S._test))
                assertTrue(S:is({ a = "ab", b = { 1, 2 } }))
                assertTrue(S:is({ a = "ab" }))
                assertFalse(S:is({ a = "a" }))
                assertFalse(S:is({ a = "ab", c = 1 }))
                assertEq(S:safeParse({ a = 1 }), false)
            end)
        end)
    end)

    test("codegen: falls back to closures when the loader rejects the code", function()
        withConfig(true, function()
            withoutLoader(function() return nil, "denied" end, function()
                local S = z.object({ a = z.string() })
                assertFalse(z._isGenerated(S._test))
                assertTrue(S:is({ a = "x" }))
                assertFalse(S:is({ a = 1 }))
            end)
        end)
    end)

    test("codegen: a schema compiled before the loader vanished keeps its generated test", function()
        withConfig(true, function()
            local S = z.object({ a = z.string() })
            local t = S._test
            assertTrue(z._isGenerated(t))
            withoutLoader(nil, function()
                assertTrue(S:is({ a = "x" }))
                assertTrue(z._isGenerated(S._test))
            end)
        end)
    end)

    test("codegen: deep schemas still validate, generated or not", function()
        withConfig(true, function()
            for _, depth in ipairs({ 60, 150 }) do
                local schema, valid, invalid = z.string(), "x", 1
                for _ = 1, depth do
                    schema = z.object({ a = schema })
                    valid = { a = valid }
                    invalid = { a = invalid }
                end
                schema = schema:limits({ maxDepth = 1000 })
                assertTrue(schema:is(valid))
                assertFalse(schema:is(invalid))
            end
        end)
    end)

    test("config: codegen = false forces closures and codegen = true restores", function()
        local previous = z.config().codegen
        local snapshot = z.config({ codegen = false })
        assertEq(snapshot.codegen, false)
        local off = z.string():min(1)
        assertFalse(z._isGenerated(off._test))
        assertTrue(off:is("a"))
        assertEq(z.config({ codegen = true }).codegen, true)
        local on = z.string():min(2)
        assertTrue(z._isGenerated(on._test))
        assertTrue(on:is("ab"))
        assertFalse(z._isGenerated(off._test))
        z.config({ codegen = previous })
    end)

    test("config: rejects bad arguments and keeps the setting", function()
        local before = z.config().codegen
        assertThrows(function() z.config("yes") end)
        assertThrows(function() z.config({ codegen = "no" }) end)
        assertThrows(function() z.config({ codgen = false }) end)
        assertEq(z.config().codegen, before)
        assertEq(z.config({}).codegen, before)
    end)

    test("codegen: _check stays on closures and agrees with the generated _test", function()
        withConfig(true, function()
            local S = z.object({ a = z.integer(), b = z.string():optional() })
            assertFalse(z._isGenerated(S._check))
            assertEq(S._check({ a = 1 }, {}, 0, nil), nil)
            assertTrue(S._check({ a = "x" }, {}, 0, nil) ~= nil)
        end)
    end)

    test("codegen: numeric rules match closures (NaN, inf, -0, floats, 2^53)", function()
        local values = listOf(nan, huge, -huge, 0, -0.0, 1, -1, 3.0, 2.5, 2 ^ 53, 2 ^ 63, 1e308,
            "1", true, {}, nil, "x")
        sameVerdict(function() return z.number() end, values)
        sameVerdict(function() return z.number():between(-1, 1) end, values)
        sameVerdict(function() return z.number():min(-huge) end, values)
        sameVerdict(function() return z.number():max(huge) end, values)
        sameVerdict(function() return z.integer() end, values)
        sameVerdict(function() return z.integer({ strict = true }) end, values)
        sameVerdict(function() return z.integer():between(0, 2 ^ 53) end, values)
        sameVerdict(function() return z.integer({ strict = true }):min(1) end, values)
        sameVerdict(function() return z.integer():optional() end, values)
        sameVerdict(function() return z.literal(3) end, values)
        sameVerdict(function() return z.literal(0) end, values)
        sameVerdict(function() return z.enum({ 1, 3, 2.5, "1" }) end, values)
    end)

    test("codegen: string, boolean and constant rules match closures", function()
        local values = listOf("", "a", "abc", "abcdef", ("x"):rep(100), 1, true, false, {}, nan, "\0", "\195\169")
        sameVerdict(function() return z.string() end, values)
        sameVerdict(function() return z.string():min(2):max(4) end, values)
        sameVerdict(function() return z.string():len(3) end, values)
        sameVerdict(function() return z.string():between(0, 1) end, values)
        sameVerdict(function() return z.boolean() end, values)
        sameVerdict(function() return z.literal(false) end, values)
        sameVerdict(function() return z.literal("a") end, values)
        sameVerdict(function() return z.enum({ "a", "abc", true }) end, values)
        sameVerdict(function() return z.any() end, values)
        sameVerdict(function() return z.never() end, values)
        sameVerdict(function() return z.never():optional() end, values)
    end)

    test("codegen: raw access versus { meta = true } matches closures", function()
        local backing = { 10, 20, 30, a = "x", b = 2 }
        local proxy = setmetatable({}, { __index = backing, __len = function() return #backing end })
        local half = setmetatable({ a = "x" }, { __index = { b = 2 } })
        local values = listOf(proxy, half, backing, {}, { a = "x", b = 2 }, { a = "x", b = 2, c = 1 })
        local function shape(opts) return z.object({ a = z.string(), b = z.integer() }, opts) end
        sameVerdict(function() return shape() end, values)
        sameVerdict(function() return shape({ meta = true }) end, values)
        sameVerdict(function() return shape():strict() end, values)
        sameVerdict(function() return shape({ meta = true }):strict() end, values)
        sameVerdict(function() return z.array(z.integer()) end, values)
        sameVerdict(function() return z.array(z.integer(), { meta = true }) end, values)
        sameVerdict(function() return z.array(z.integer(), { meta = true }):min(4) end, values)
        sameVerdict(function() return z.array(z.integer()):len(0) end, values)
    end)

    test("codegen: array holes, stray keys and bounds match closures", function()
        local values = listOf(
            {}, { 1 }, { 1, 2, 3 }, { 1, nil, 3 }, { [2] = 1 }, { 1, 2, x = 3 }, { 1, 2, [4] = 4 },
            { [0] = 1, 1 }, { [-1] = 1 }, { [1.5] = 1 }, { 1, "a" }, { "a" }, "x", 1, nil)
        sameVerdict(function() return z.array(z.integer()) end, values)
        sameVerdict(function() return z.array(z.integer()):max(2) end, values)
        sameVerdict(function() return z.array(z.integer()):min(1):max(1) end, values)
        sameVerdict(function() return z.array(z.any()) end, values)
        sameVerdict(function() return z.array(z.integer():optional()) end, values)
        sameVerdict(function() return z.array(z.array(z.integer())) end, values)
        sameVerdict(function() return z.array(z.integer(), { meta = true }) end, values)
        sameVerdict(function() return z.array(z.never()) end, values)
    end)
end
