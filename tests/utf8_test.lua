return function(env)
    local test, z = env.test, env.z
    local assertEq, assertTrue, assertFalse = env.assertEq, env.assertTrue, env.assertFalse
    local assertThrows, assertDeepEq = env.assertThrows, env.assertDeepEq

    local function firstIssue(schema, input)
        local ok, value, err = schema:safeParse(input)
        assertFalse(ok)
        assertEq(value, nil)
        assertTrue(z.isError(err))
        return err.issues[1]
    end

    local valid = {
        ["empty"] = "",
        ["ascii"] = "abc",
        ["nul"] = "a\0b",
        ["del"] = "\127",
        ["U+0080"] = "\194\128",
        ["U+00E9"] = "h\195\169llo",
        ["U+07FF"] = "\223\191",
        ["U+0800"] = "\224\160\128",
        ["U+20AC"] = "\226\130\172",
        ["U+D7FF"] = "\237\159\191",
        ["U+E000"] = "\238\128\128",
        ["U+FFFD"] = "\239\191\189",
        ["U+FFFF"] = "\239\191\191",
        ["U+10000"] = "\240\144\128\128",
        ["U+1F600"] = "\240\159\152\128",
        ["U+10FFFF"] = "\244\143\191\191",
        ["mixed"] = "a\195\169b\226\130\172c\240\159\152\128d",
    }

    local invalid = {
        ["lone continuation"] = "\128",
        ["lone continuation 0xBF"] = "\191",
        ["overlong C0 80"] = "\192\128",
        ["overlong C1 BF"] = "\193\191",
        ["overlong E0 80 80"] = "\224\128\128",
        ["overlong E0 9F BF"] = "\224\159\191",
        ["overlong F0 80 80 80"] = "\240\128\128\128",
        ["overlong F0 8F BF BF"] = "\240\143\191\191",
        ["surrogate D800"] = "\237\160\128",
        ["surrogate DBFF"] = "\237\175\191",
        ["surrogate DC00"] = "\237\176\128",
        ["surrogate DFFF"] = "\237\191\191",
        ["above U+10FFFF"] = "\244\144\128\128",
        ["F5 lead"] = "\245\128\128\128",
        ["F7 lead"] = "\247\191\191\191",
        ["5-byte form"] = "\248\136\128\128\128",
        ["6-byte form"] = "\252\132\128\128\128\128",
        ["FE"] = "\254",
        ["FF"] = "\255",
        ["truncated 2-byte"] = "\194",
        ["truncated 3-byte"] = "\226\130",
        ["truncated 3-byte lead only"] = "\226",
        ["truncated 4-byte"] = "\240\159\152",
        ["truncated after ascii"] = "abc\226\130",
        ["2-byte then ascii"] = "\194A",
        ["3-byte then ascii"] = "\226\130A",
        ["4-byte then ascii"] = "\240\159\152A",
        ["continuation bad second"] = "\226\65\172",
        ["continuation bad third"] = "\240\159\65\128",
        ["invalid after valid"] = "h\195\169llo\255",
        ["invalid before valid"] = "\255h\195\169llo",
        ["continuation after ascii"] = "abc\128def",
    }

    test("bytes accepts every string and refuses other types", function()
        local S = z.bytes()
        assertTrue(S:is("")); assertTrue(S:is("abc")); assertTrue(S:is("\255\254\0\128"))
        for _, bad in pairs(invalid) do assertTrue(S:is(bad)) end
        assertFalse(S:is(1)); assertFalse(S:is(nil)); assertFalse(S:is(true)); assertFalse(S:is({}))
        assertFalse(S:is(print))
    end)

    test("bytes min, max, len and between count bytes", function()
        assertTrue(z.bytes():len(2):is("\195\169"))
        assertFalse(z.bytes():len(1):is("\195\169"))
        assertTrue(z.bytes():max(2):is("\195\169")); assertFalse(z.bytes():max(1):is("\195\169"))
        assertTrue(z.bytes():min(2):is("\195\169")); assertFalse(z.bytes():min(3):is("\195\169"))
        local b = z.bytes():between(2, 4)
        assertFalse(b:is("a")); assertTrue(b:is("ab")); assertTrue(b:is("abcd")); assertFalse(b:is("abcde"))
    end)

    test("bytes agrees with string on every input and bound", function()
        local inputs = { "", "a", "abc", "\255", "\195\169\195\169", 1, true, {}, false }
        local pairsOf = {
            { z.bytes(), z.string() },
            { z.bytes():min(2), z.string():min(2) },
            { z.bytes():max(2), z.string():max(2) },
            { z.bytes():len(3), z.string():len(3) },
            { z.bytes():between(1, 3):optional(), z.string():between(1, 3):optional() },
        }
        for _, pair in ipairs(pairsOf) do
            for _, input in ipairs(inputs) do
                assertEq(pair[1]:is(input), pair[2]:is(input))
            end
            assertEq(pair[1]:is(nil), pair[2]:is(nil))
        end
    end)

    test("bytes is generated by codegen, names itself in errors and has the bound methods", function()
        local S = z.bytes():min(1)
        if z.config().codegen then assertTrue(z._isGenerated(S._test)) end
        assertEq(tostring(S), "zigo.bytes")
        assertDeepEq(firstIssue(S, 1), { path = {}, code = "invalid_type", expected = "bytes", got = "number" })
        assertDeepEq(firstIssue(S, ""), { path = {}, code = "too_small", expected = 1, got = 0, type = "bytes" })
        assertThrows(function() z.bytes():min(-1) end)
        assertThrows(function() z.bytes():len(1.5) end)
    end)

    test("utf8 accepts every well formed sequence up to U+10FFFF", function()
        local S = z.utf8()
        for name, s in pairs(valid) do
            if not S:is(s) then error("expected valid: " .. name, 0) end
        end
    end)

    test("utf8 refuses overlong forms, surrogates, values past U+10FFFF and truncated sequences", function()
        local S = z.utf8()
        for name, s in pairs(invalid) do
            if S:is(s) then error("expected invalid: " .. name, 0) end
        end
    end)

    test("utf8 refuses other types", function()
        local S = z.utf8()
        assertFalse(S:is(1)); assertFalse(S:is(nil)); assertFalse(S:is(true)); assertFalse(S:is({}))
        assertFalse(S:is(print))
    end)

    test("utf8 verdict is the same with the bounds, whatever the length of the string", function()
        local loose = z.utf8():max(1000000)
        for name, s in pairs(valid) do
            if not loose:is(s) then error("expected valid with max: " .. name, 0) end
        end
        for name, s in pairs(invalid) do
            if loose:is(s) then error("expected invalid with max: " .. name, 0) end
        end
    end)

    test("utf8 long strings: ascii fast path, long multibyte runs and a bad byte at the very end", function()
        local S = z.utf8()
        assertTrue(S:is(("a"):rep(100000)))
        assertTrue(S:is(("\226\130\172"):rep(30000)))
        assertTrue(S:is(("ab\195\169"):rep(30000)))
        assertFalse(S:is(("a"):rep(100000) .. "\128"))
        assertFalse(S:is(("a"):rep(100000) .. "\226\130"))
        assertFalse(S:is(("\226\130\172"):rep(30000) .. "\255"))
        assertFalse(S:is("\255" .. ("a"):rep(100000)))
    end)

    test("utf8 min, max, len and between count characters, not bytes", function()
        local word = "h\195\169llo"
        assertEq(#word, 6)
        assertTrue(z.utf8():len(5):is(word)); assertFalse(z.utf8():len(6):is(word))
        assertTrue(z.utf8():max(5):is(word)); assertFalse(z.utf8():max(4):is(word))
        assertTrue(z.utf8():min(5):is(word)); assertFalse(z.utf8():min(6):is(word))
        assertFalse(z.string():len(5):is(word))
        local han = "\230\151\165\230\156\172\232\170\158"
        assertTrue(z.utf8():len(3):is(han)); assertTrue(z.utf8():between(1, 3):is(han))
        assertFalse(z.utf8():max(2):is(han))
        local emoji = "\240\159\152\128"
        assertTrue(z.utf8():len(1):is(emoji)); assertFalse(z.utf8():len(4):is(emoji))
        assertTrue(z.utf8():len(0):is("")); assertFalse(z.utf8():len(0):is("a"))
        assertTrue(z.utf8():len(7):is("a\195\169b\226\130\172c\240\159\152\128d"))
        assertTrue(z.utf8():min(3):max(32):is("abc"))
        assertFalse(z.utf8():min(3):max(32):is("ab"))
        assertFalse(z.utf8():min(3):max(32):is(("a"):rep(33)))
    end)

    test("utf8 reports invalid_type utf8 for a bad encoding, then length bounds in characters", function()
        local S = z.utf8():min(2):max(4)
        assertDeepEq(firstIssue(S, 5), { path = {}, code = "invalid_type", expected = "utf8", got = "number" })
        assertDeepEq(firstIssue(S, "\255\255"), { path = {}, code = "invalid_type", expected = "utf8", got = "bytes" })
        assertDeepEq(firstIssue(S, "\195\169"), { path = {}, code = "too_small", expected = 2, got = 1, type = "utf8" })
        local over = firstIssue(S, "\195\169\195\169\195\169\195\169\195\169")
        assertDeepEq(over, { path = {}, code = "too_big", expected = 4, got = 5, type = "utf8" })
        local exact = firstIssue(z.utf8():len(3), "\195\169")
        assertEq(exact.code, "too_small"); assertEq(exact.exact, true); assertEq(exact.got, 1)
        local _, _, err = z.utf8():min(2):safeParse("\195\169")
        assertEq(err:format(), "<root>: Expected length of at least 2, got 1")
    end)

    test("utf8 works as optional field, in objects and arrays, and is generated by codegen", function()
        local S = z.object({ name = z.utf8():min(1):max(8), nick = z.utf8():optional() })
        assertTrue(S:is({ name = "h\195\169" })); assertTrue(S:is({ name = "a", nick = "\240\159\152\128" }))
        assertFalse(S:is({ name = "" })); assertFalse(S:is({ name = "\255" }))
        assertFalse(S:is({ name = "ab", nick = "\237\160\128" }))
        assertFalse(S:is({ name = ("\195\169"):rep(9) }))
        assertTrue(S:is({ name = ("\195\169"):rep(8) }))
        if z.config().codegen then assertTrue(z._isGenerated(S._test)) end
        local A = z.array(z.utf8())
        assertTrue(A:is({ "a", "\195\169" })); assertFalse(A:is({ "a", "\192\128" }))
    end)

    test("utf8 with refine keeps checking the encoding first", function()
        local S = z.utf8():refine(function(s) return #s > 0 end)
        assertTrue(S:is("a")); assertFalse(S:is("")); assertFalse(S:is("\255"))
    end)

    test("utf8 agrees between every sequence length and its neighbours one byte off", function()
        local S = z.utf8()
        local samples = { "a", "\195\169", "\226\130\172", "\240\159\152\128" }
        for _, s in ipairs(samples) do
            assertTrue(S:is(s))
            assertFalse(S:is(s:sub(1, #s - 1)) and #s > 1)
            assertFalse(S:is(s .. "\128"))
            assertFalse(S:is("\128" .. s))
        end
    end)
end
