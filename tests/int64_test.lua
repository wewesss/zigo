return function(env)
    local test, z = env.test, env.z
    local assertEq, assertTrue, assertFalse = env.assertEq, env.assertTrue, env.assertFalse
    local assertThrows, assertDeepEq = env.assertThrows, env.assertDeepEq

    local huge = math.huge
    local nan = 0 / 0
    local P53 = 2 ^ 53

    local ffi
    if jit then
        local ok, lib = pcall(require, "ffi")
        if ok then ffi = lib end
    end
    local native = math.type ~= nil and math.maxinteger ~= nil and math.maxinteger > P53
    local loader = loadstring or load

    local function firstIssue(schema, input)
        local ok, value, err = schema:safeParse(input)
        assertFalse(ok)
        assertEq(value, nil)
        assertTrue(z.isError(err))
        return err.issues[1]
    end

    local function native64(src)
        return assert(loader("return " .. src))()
    end

    test("int64 accepts integral numbers up to 2^53 on every runtime", function()
        local S = z.int64()
        assertTrue(S:is(0)); assertTrue(S:is(1)); assertTrue(S:is(-1)); assertTrue(S:is(3.0))
        assertTrue(S:is(P53)); assertTrue(S:is(-P53)); assertTrue(S:is(2 ^ 40 + 5))
        assertTrue(S:is(-0.0))
    end)

    test("int64 refuses numbers that are fractional, non finite or past 2^53", function()
        local S = z.int64()
        assertFalse(S:is(1.5)); assertFalse(S:is(-0.5)); assertFalse(S:is(nan))
        assertFalse(S:is(huge)); assertFalse(S:is(-huge))
        assertFalse(S:is(P53 + 2)); assertFalse(S:is(-P53 - 2)); assertFalse(S:is(2 ^ 63)); assertFalse(S:is(1e300))
    end)

    test("int64 refuses strings, booleans, nil, tables and functions", function()
        local S = z.int64()
        for _, bad in ipairs({ "1", "", "9007199254740993", true, false, {}, print }) do
            assertFalse(S:is(bad))
        end
        assertFalse(S:is(nil))
    end)

    test("int64 on 5.3+ accepts every native integer and refuses floats past 2^53", function()
        if not native then return end
        local S = z.int64()
        assertTrue(S:is(math.maxinteger)); assertTrue(S:is(math.mininteger))
        assertTrue(S:is(native64("9007199254740993"))); assertTrue(S:is(native64("-9007199254740993")))
        assertTrue(S:is(native64("9007199254740992")))
        assertFalse(S:is(9007199254740994.0)); assertFalse(S:is(-9007199254740994.0))
        assertFalse(S:is(9.3e18))
    end)

    test("int64 on LuaJIT accepts cdata int64_t and refuses uint64_t and other cdata", function()
        if not ffi then return end
        local S = z.int64()
        assertTrue(S:is(ffi.new("int64_t", 1)))
        assertTrue(S:is(ffi.new("int64_t", 0)))
        assertTrue(S:is(native64("1LL")))
        assertTrue(S:is(native64("-1LL")))
        assertTrue(S:is(native64("9007199254740993LL")))
        assertTrue(S:is(native64("9223372036854775807LL")))
        assertTrue(S:is(native64("-9223372036854775807LL - 1")))
        assertFalse(S:is(native64("1ULL")))
        assertFalse(S:is(native64("18446744073709551615ULL")))
        assertFalse(S:is(ffi.new("uint64_t", 5)))
        assertFalse(S:is(ffi.new("int32_t", 5)))
        assertFalse(S:is(ffi.new("double", 5)))
        assertFalse(S:is(ffi.new("int64_t[1]", 5)))
        assertFalse(S:is(ffi.cast("void *", 0)))
        assertFalse(S:is(ffi.new("struct { int a; }", { 1 })))
    end)

    test("int64 inside an object and an array, with optional", function()
        local S = z.object({ id = z.int64(), next = z.int64():optional() })
        assertTrue(S:is({ id = 5 })); assertTrue(S:is({ id = 5, next = -7 }))
        assertFalse(S:is({ id = 5.5 })); assertFalse(S:is({ id = 5, next = "1" })); assertFalse(S:is({}))
        local A = z.array(z.int64())
        assertTrue(A:is({ 1, 2, 3 })); assertFalse(A:is({ 1, P53 + 2 }))
        if ffi then
            assertTrue(A:is({ native64("1LL"), 2 }))
            assertFalse(A:is({ native64("1ULL"), 2 }))
            assertTrue(S:is({ id = native64("9007199254740993LL") }))
        end
    end)

    test("int64 reports invalid_type with the int64 name", function()
        local S = z.int64()
        assertDeepEq(firstIssue(S, "1"), { path = {}, code = "invalid_type", expected = "int64", got = "string" })
        assertDeepEq(firstIssue(S, 1.5), { path = {}, code = "invalid_type", expected = "int64", got = "float" })
        assertDeepEq(firstIssue(S, 2 ^ 60), { path = {}, code = "invalid_type", expected = "int64", got = "float" })
        assertEq(firstIssue(S, nan).got, "nan")
        assertEq(firstIssue(S, huge).got, "inf")
        if ffi then
            assertEq(firstIssue(S, native64("1ULL")).got, "cdata")
        end
    end)

    test("int64 is generated by codegen and has no bounds methods", function()
        local S = z.int64()
        if z.config().codegen then assertTrue(z._isGenerated(S._test)) end
        assertThrows(function() S:min(1) end)
        assertThrows(function() S:max(1) end)
        assertEq(tostring(S), "zigo.int64")
    end)

    test("int64 rejects an options argument that is not a table", function()
        assertThrows(function() z.int64(true) end)
        assertThrows(function() z.int64("fromString") end)
    end)

    local function viaString(input)
        return z.int64({ fromString = true }):safeParse(input)
    end

    test("int64 fromString: without the option strings are refused", function()
        assertFalse(z.int64():is("5"))
        assertFalse(z.int64({}):is("5"))
        assertFalse(z.int64({ fromString = false }):is("5"))
        assertTrue(z.int64({ fromString = true }):is("5"))
    end)

    test("int64 fromString returns one fixed form per runtime", function()
        local ok, v = viaString("42")
        assertTrue(ok)
        if ffi then
            assertTrue(ffi.istype("int64_t", v))
            assertEq(tostring(v), "42LL")
        elseif native then
            assertEq(math.type(v), "integer"); assertEq(v, 42)
        else
            assertEq(type(v), "number"); assertEq(v, 42)
        end
        ok, v = viaString("-42")
        assertTrue(ok)
        if ffi then assertEq(tostring(v), "-42LL") else assertEq(v, -42) end
        ok, v = viaString("0")
        assertTrue(ok)
        if ffi then assertTrue(ffi.istype("int64_t", v)) else assertEq(v, 0) end
    end)

    test("int64 fromString keeps every digit of a value past 2^53 where the runtime can", function()
        local ok, v = viaString("9007199254740993")
        if ffi then
            assertTrue(ok); assertEq(tostring(v), "9007199254740993LL")
        elseif native then
            assertTrue(ok); assertEq(v, native64("9007199254740993")); assertEq(math.type(v), "integer")
        else
            assertFalse(ok)
        end
        ok, v = viaString("9223372036854775807")
        if ffi then
            assertTrue(ok); assertEq(tostring(v), "9223372036854775807LL")
        elseif native then
            assertTrue(ok); assertEq(v, math.maxinteger)
        else
            assertFalse(ok)
        end
        ok, v = viaString("-9223372036854775808")
        if ffi then
            assertTrue(ok); assertEq(tostring(v), "-9223372036854775808LL")
        elseif native then
            assertTrue(ok); assertEq(v, math.mininteger)
        else
            assertFalse(ok)
        end
    end)

    test("int64 fromString: values past the int64 range give too_big or too_small", function()
        local S = z.int64({ fromString = true })
        for _, s in ipairs({
            "9223372036854775808", "9223372036854775809", "18446744073709551615",
            "123456789012345678901234567890", ("9"):rep(400), "0009223372036854775808",
        }) do
            local issue = firstIssue(S, s)
            assertEq(issue.code, "too_big"); assertEq(issue.type, "integer")
        end
        for _, s in ipairs({ "-9223372036854775809", "-18446744073709551616", "-" .. ("9"):rep(400) }) do
            local issue = firstIssue(S, s)
            assertEq(issue.code, "too_small")
        end
        assertFalse(S:is("9223372036854775808")); assertFalse(S:is("-9223372036854775809"))
    end)

    test("int64 fromString: leading zeros and minus zero are plain digits", function()
        local S = z.int64({ fromString = true })
        local ok, v = S:safeParse("007")
        assertTrue(ok); assertEq(tostring(v):gsub("LL$", ""), "7")
        ok, v = S:safeParse("-0")
        assertTrue(ok); assertEq(tostring(v):gsub("LL$", ""), "0")
        ok, v = S:safeParse("0000000000000000000000000012")
        assertTrue(ok); assertEq(tostring(v):gsub("LL$", ""), "12")
        ok = S:safeParse("00000000000000000000000000000000")
        assertTrue(ok)
    end)

    test("int64 fromString: invalid digit strings give invalid_type on int64", function()
        local S = z.int64({ fromString = true })
        for _, s in ipairs({
            "", " ", "abc", "1.5", "1.0", " 1", "1 ", "+1", "0x10", "1e3", "--1", "-", "1-", "1_000",
            "12a", "\t1", "1\n", "1\0", "nan", "inf", "-inf", "1,5", "\226\130\172",
        }) do
            local issue = firstIssue(S, s)
            assertEq(issue.code, "invalid_type"); assertEq(issue.expected, "int64"); assertEq(issue.got, "string")
        end
    end)

    test("int64 fromString: values that are not strings go through the plain int64 rule unchanged", function()
        local S = z.int64({ fromString = true })
        local ok, v = S:safeParse(5)
        assertTrue(ok); assertEq(v, 5)
        ok, v = S:safeParse(-P53)
        assertTrue(ok); assertEq(v, -P53)
        for _, bad in ipairs({ 1.5, nan, huge, P53 + 2, true, false, {}, print }) do
            assertEq(firstIssue(S, bad).code, "invalid_type")
        end
        assertEq(firstIssue(S, nil).code, "invalid_type")
        if ffi then
            local c = ffi.new("int64_t", 9)
            ok, v = S:safeParse(c)
            assertTrue(ok); assertTrue(rawequal(v, c))
            assertFalse(S:is(native64("1ULL")))
        end
    end)

    test("int64 fromString composes with optional, objects and arrays", function()
        local S = z.object({ id = z.int64({ fromString = true }), next = z.int64({ fromString = true }):optional() })
        local ok, out = S:safeParse({ id = "12", next = "-3" })
        assertTrue(ok)
        assertEq(tostring(out.id):gsub("LL$", ""), "12")
        assertEq(tostring(out.next):gsub("LL$", ""), "-3")
        ok, out = S:safeParse({ id = "12" })
        assertTrue(ok); assertEq(out.next, nil)
        local bad, _, err = S:safeParse({ id = "x", next = "9223372036854775808" })
        assertFalse(bad)
        assertEq(#err.issues, 2)
        assertDeepEq(err.issues[1].path, { "id" })
        assertDeepEq(err.issues[2].path, { "next" })
        assertEq(err.issues[2].code, "too_big")
        local A = z.array(z.int64({ fromString = true }))
        ok, out = A:safeParse({ "1", "2", 3 })
        assertTrue(ok); assertEq(#out, 3)
    end)

    test("int64 fromString messages read as a range error", function()
        local _, _, err = z.int64({ fromString = true }):safeParse("9223372036854775808")
        local text = err:format():gsub("LL", "")
        local bound = (native or ffi) and "9223372036854775807" or tostring(P53)
        assertEq(text, "<root>: Expected value of at most " .. bound .. ", got " .. tostring(2 ^ 63))
    end)

    test("int64 plain-number runtime: a LuaJIT without ffi follows the 2^53 rules", function()
        if not jit then return end
        local saved = jit
        jit = nil
        local ok, c = pcall(dofile, "zigo/util/compat.lua")
        jit = saved
        assertTrue(ok)
        assertEq(c.ffi, nil)
        assertEq(c.nativeInt64, false)
        assertTrue(c.isInt64(P53)); assertTrue(c.isInt64(-P53)); assertTrue(c.isInt64(3.0))
        assertFalse(c.isInt64(P53 + 2)); assertFalse(c.isInt64(1.5)); assertFalse(c.isInt64(nan))
        assertFalse(c.isInt64(huge)); assertFalse(c.isInt64("1"))
        if ffi then assertFalse(c.isInt64(ffi.new("int64_t", 1))) end
        local r, v = c.parseInt64("9007199254740992")
        assertTrue(r); assertEq(v, P53)
        r, v = c.parseInt64("-9007199254740992")
        assertTrue(r); assertEq(v, -P53)
        local code, limit
        r, code, limit = c.parseInt64("9007199254740993")
        assertFalse(r); assertEq(code, "too_big"); assertEq(limit, P53)
        r, code, limit = c.parseInt64("-9007199254740993")
        assertFalse(r); assertEq(code, "too_small"); assertEq(limit, -P53)
        r, code = c.parseInt64(("9"):rep(400))
        assertFalse(r); assertEq(code, "too_big")
        r, code = c.parseInt64("1.5")
        assertFalse(r); assertEq(code, nil)
    end)
end
